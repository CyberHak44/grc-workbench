// Converts the CSV data files into .js files so the page works when opened from disk (file://).
// Run: node tools/build-data.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');

function parseLine(line) {
  const out = []; let cur = ''; let q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) {
      if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (c === '"') q = false;
      else cur += c;
    } else if (c === '"') q = true;
    else if (c === ',') { out.push(cur); cur = ''; }
    else cur += c;
  }
  out.push(cur);
  return out;
}

function build(csvName, jsName, globalName, idKey, expected) {
  const text = fs.readFileSync(path.join(root, 'data', csvName), 'utf8').trim();
  const [header, ...lines] = text.split(/\r?\n/);
  const keys = parseLine(header);
  const rows = lines.map((l) => { const v = parseLine(l); const o = {}; keys.forEach((k, i) => { o[k] = v[i] || ''; }); return o; });
  const ids = new Set(rows.map((r) => r[idKey]));
  if (rows.length !== expected || ids.size !== expected) {
    console.error(csvName + ': expected ' + expected + ' unique rows, got ' + rows.length + ' rows and ' + ids.size + ' unique IDs');
    process.exit(1);
  }
  const banner = '// Generated by tools/build-data.js from data/' + csvName + '. Do not edit by hand.\n';
  fs.writeFileSync(path.join(root, 'data', jsName), banner + 'window.' + globalName + ' = ' + JSON.stringify(rows, null, 1) + ';\n');
  console.log('Wrote ' + rows.length + ' rows to data/' + jsName);
}

build('controls.csv', 'controls.js', 'GRC_CONTROLS', 'control_id', 93);
build('cbuae-crosswalk.csv', 'cbuae.js', 'GRC_CBUAE', 'id', 39);
