// Converts data/controls.csv into data/controls.js so the page works when opened from disk (file://).
// Run: node tools/build-controls.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const text = fs.readFileSync(path.join(root, 'data', 'controls.csv'), 'utf8').trim();

function parseLine(line) {
  const out = []; let cur = ''; let q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) {
      if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (c === '"') q = false;
      else cur += c;
    } else if (c === '"') q = true;
    else if (c === ',') { out.push(cur); cur = ''; }
    else cur += c;
  }
  out.push(cur);
  return out;
}

const [header, ...lines] = text.split(/\r?\n/);
const keys = parseLine(header);
const rows = lines.map(l => {
  const v = parseLine(l); const o = {};
  keys.forEach((k, i) => { o[k] = v[i] || ''; });
  return o;
});

const ids = new Set(rows.map(r => r.control_id));
if (rows.length !== 93 || ids.size !== 93) {
  console.error(`Expected 93 unique controls, got ${rows.length} rows and ${ids.size} unique IDs`);
  process.exit(1);
}

const banner = '// Generated by tools/build-controls.js from data/controls.csv. Do not edit by hand.\n';
fs.writeFileSync(path.join(root, 'data', 'controls.js'), banner + 'window.GRC_CONTROLS = ' + JSON.stringify(rows, null, 1) + ';\n');
console.log(`Wrote ${rows.length} controls to data/controls.js`);
